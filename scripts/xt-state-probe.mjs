import { chromium } from '@playwright/test';
const ctx = await chromium.launchPersistentContext('/Users/lukadadiani/Documents/Client/.xt-session',{headless:true,viewport:{width:1440,height:900},args:['--no-first-run']});
const p = ctx.pages()[0] ?? await ctx.newPage();
let azure=0; p.on('response',r=>{ if(/blob\.core\.windows\.net/.test(r.url())) azure++; });
await p.goto('http://localhost:8000',{waitUntil:'networkidle',timeout:30000}).catch(()=>{});
await p.waitForTimeout(9000);
const authBtn=await p.locator('button:has-text("Authenticate")').count();
const domBytes=(await p.content()).length;
const hasDash=await p.getByText('Dashboard',{exact:false}).count();
const hasNewQuote=await p.getByText('New quote',{exact:false}).count();
console.log(JSON.stringify({authBtn,domBytes,hasDash,hasNewQuote,azureImgReqs:azure},null,2));
await ctx.close();
