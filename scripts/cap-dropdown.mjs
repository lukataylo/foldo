import { chromium } from '@playwright/test';
const b=await chromium.launch();
const ctx=await b.newContext({viewport:{width:1500,height:950}});
await ctx.addInitScript(()=>{try{localStorage.setItem('foldo:cookie-acked','1');localStorage.setItem('foldo:demoUserId','u-you');}catch{}});
const p=await ctx.newPage();
await p.goto('http://localhost:5273/board/board-acme-landing',{waitUntil:'domcontentloaded',timeout:30000});
await p.waitForTimeout(3000);
await p.getByRole('button',{name:/Switch demo user/i}).click().catch(async()=>{ await p.locator('button:has-text("You")').first().click(); });
await p.waitForTimeout(800);
const names = await p.locator('text=Demo as').locator('xpath=..').locator('button').allInnerTexts().catch(()=>[]);
await p.screenshot({path:'/tmp/foldo-e2e/xt/dropdown.png',clip:{x:1080,y:0,width:420,height:340}});
console.log('picker entries:', names.map(n=>n.replace(/\s+/g,' ').trim()));
await b.close();
